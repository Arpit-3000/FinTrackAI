// Helper function to get category details
export const getCategoryDetails = (categoryId: string, type: 'income' | 'expense') => {
  const categoryList = type === 'income' ? categories.income : categories.expense;
  return categoryList.find(cat => cat.id === categoryId) || categoryList[categoryList.length - 1];
};
